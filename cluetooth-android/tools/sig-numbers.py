#!/usr/bin/env python3
"""Export the Bluetooth SIG assigned numbers the device sheet shows into one small asset.

Reads a snapshot of https://bitbucket.org/bluetooth-SIG/public (the YAML files under
assigned_numbers/, as fetched by the kb tooling into ~/.local/state/cluetooth-kb/sig/<commit>/)
and writes app/src/main/assets/sig-numbers.tsv:

    company     004C   Apple, Inc.
    uuid16      180D   Heart Rate          (service UUIDs, then member UUIDs)
    appearance  0083   Computer: Laptop    (category << 6 | subcategory)
    adtype      01     Flags

Usage: sig-numbers.py [SIG_DIR] [OUT]
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "app/src/main/assets/sig-numbers.tsv"


def default_dir() -> pathlib.Path:
    base = pathlib.Path.home() / ".local/state/cluetooth-kb/sig"
    snapshots = sorted((p for p in base.iterdir() if (p / "VERSION.json").exists()), key=lambda p: p.stat().st_mtime)
    if not snapshots:
        sys.exit(f"no SIG snapshot under {base}")
    return snapshots[-1]


def unquote(s: str) -> str:
    s = s.strip()
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "'\"":
        s = s[1:-1]
        s = s.replace("''", "'") if s and "'" in s else s
    return s.replace("\t", " ")


def pairs(path: pathlib.Path, key: str) -> list[tuple[int, str]]:
    """Every `- <key>: 0x..` item with the `name:` that follows it (flat lists)."""
    out: list[tuple[int, str]] = []
    value = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.lstrip().startswith("#"):
            continue
        m = re.match(rf"\s*-\s*{key}:\s*(0x[0-9A-Fa-f]+)\s*$", line)
        if m:
            value = int(m.group(1), 16)
            continue
        m = re.match(r"\s*name:\s*(.+)$", line)
        if m and value is not None:
            out.append((value, unquote(m.group(1))))
            value = None
    return out


def appearances(path: pathlib.Path) -> list[tuple[int, str]]:
    out: list[tuple[int, str]] = []
    category = None
    category_name = ""
    pending_sub = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.lstrip().startswith("#"):
            continue
        m = re.match(r"\s*-\s*category:\s*(0x[0-9A-Fa-f]+)\s*$", line)
        if m:
            category, pending_sub = int(m.group(1), 16), None
            continue
        m = re.match(r"\s*-\s*value:\s*(0x[0-9A-Fa-f]+)\s*$", line)
        if m:
            pending_sub = int(m.group(1), 16)
            continue
        m = re.match(r"\s*name:\s*(.+)$", line)
        if m and category is not None:
            name = unquote(m.group(1))
            if pending_sub is None:
                category_name = name
                out.append((category << 6, name))
            else:
                out.append(((category << 6) | pending_sub, f"{category_name}: {name}"))
                pending_sub = None
    return out


def main() -> None:
    sig = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else default_dir()
    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUT
    version = json.loads((sig / "VERSION.json").read_text(encoding="utf-8"))
    rows: list[str] = []
    rows += [f"company\t{v:04X}\t{n}" for v, n in sorted(pairs(sig / "company_identifiers.yaml", "value"))]
    seen: set[int] = set()
    for f in ("service_uuids.yaml", "member_uuids.yaml"):
        for v, n in sorted(pairs(sig / f, "uuid")):
            if v not in seen:
                seen.add(v)
                rows.append(f"uuid16\t{v:04X}\t{n}")
    rows += [f"appearance\t{v:04X}\t{n}" for v, n in sorted(appearances(sig / "appearance_values.yaml"))]
    rows += [f"adtype\t{v:02X}\t{n}" for v, n in sorted(pairs(sig / "ad_types.yaml", "value"))]
    header = [
        f"# Bluetooth SIG assigned numbers from {version['repo']} at {version['commit']} ({version['date'][:10]}).",
        "# Generated by tools/sig-numbers.py; do not edit. Copyright Bluetooth SIG, Inc.; provided \"as is\" (see the source files).",
    ]
    out.write_text("\n".join(header + rows) + "\n", encoding="utf-8")
    kinds = {k: sum(r.startswith(k + "\t") for r in rows) for k in ("company", "uuid16", "appearance", "adtype")}
    print(f"{out}: {kinds}")


if __name__ == "__main__":
    main()
