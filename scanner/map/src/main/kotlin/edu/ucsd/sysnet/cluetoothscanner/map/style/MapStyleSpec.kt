package edu.ucsd.sysnet.cluetoothscanner.map.style

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.double
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive

enum class MapTheme(val key: String) { Light("light"), Dark("dark") }

/** A GeoJSON source of map-style.js `sources()`; data is always set at runtime. */
data class SourceSpec(val id: String, val cluster: Boolean, val clusterRadius: Int?, val clusterMaxZoom: Int?)

/** One property to set for the selection: map-style.js `selectionProps` → [layer, kind, property, value]. */
data class SelectionProp(val layer: String, val kind: Kind, val property: String?, val value: JsonElement) {
    enum class Kind { Paint, Filter }
}

/**
 * The parsed design/ui-v2/map-style.json (generated by export.mjs from map-style.js and tokens.css). Everything
 * the map draws comes from here unchanged (M-2); the only additions are the `cells` source and its two layers,
 * cloned from `clusters`/`cluster-count` with identical paint (docs/v2-api.md §3.7, §6.6).
 */
class MapStyleSpec private constructor(private val root: JsonObject) {

    fun baseStyleUrl(theme: MapTheme): String = root.obj("baseStyle").getValue(theme.key).jsonPrimitive.content

    /** The style's sources in declaration order, plus `cells`. */
    val sources: List<SourceSpec> = root.obj("sources").map { (id, v) ->
        val o = v.jsonObject
        SourceSpec(
            id = id,
            cluster = o["cluster"]?.jsonPrimitive?.boolean ?: false,
            clusterRadius = o["clusterRadius"]?.jsonPrimitive?.int,
            clusterMaxZoom = o["clusterMaxZoom"]?.jsonPrimitive?.int,
        )
    } + SourceSpec(CELLS, cluster = false, clusterRadius = null, clusterMaxZoom = null)

    /** The JSON layers of map-style.json for [theme], bottom to top, exactly as exported. */
    fun styleLayers(theme: MapTheme): List<JsonObject> = root.obj("layers").getValue(theme.key).jsonArray.map { it.jsonObject }

    /** The layers to add, bottom to top: [styleLayers] with `cells` and `cell-count` right after `cluster-count`. */
    fun layers(theme: MapTheme): List<JsonObject> {
        val base = styleLayers(theme)
        val clusters = base.single { it.id == "clusters" }
        val count = base.single { it.id == "cluster-count" }
        val out = base.toMutableList()
        out.addAll(out.indexOf(count) + 1, listOf(clusters.cloneAs(CELLS_LAYER), count.cloneAs(CELL_COUNT_LAYER)))
        return out
    }

    /** The subset the R-5 mini map draws (the prototype's `miniMap`: route, end-dots, end-labels). */
    fun miniMapLayers(theme: MapTheme): List<JsonObject> = styleLayers(theme).filter { it.id in MINI_MAP_LAYERS }

    private val runtime = root.obj("runtime")

    /** The one font map-style.js names for its labels (text-font), the same in both themes. */
    val font: String = root.obj("values").getValue("light").jsonObject.getValue("font").jsonPrimitive.content

    /** M-8: line-opacity of `route` for one session and for All sessions (every route, fainter). */
    val routeOpacitySession: Double = runtime.obj("routeOpacity").getValue("session").jsonPrimitive.double
    val routeOpacityAllSessions: Double = runtime.obj("routeOpacity").getValue("allSessions").jsonPrimitive.double

    /** `--dim`: the opacity of everything that is not the selected device (M-6). */
    val dim: Double = runtime.getValue("dim").jsonPrimitive.double

    /** The `ends` feature properties: Start, then End. */
    val endProperties: List<JsonObject> = runtime.getValue("ends").jsonArray.map { it.jsonObject }

    /**
     * map-style.js `selectionProps(addr, dim)`, from the exported templates. addr null clears. The `cells` and
     * `cell-count` clones follow `clusters` and `cluster-count`, so every other point, cluster, cell and count fades.
     */
    fun selection(addr: String?): List<SelectionProp> {
        val sel = runtime.obj("selection")
        val template = if (addr == null) sel.getValue("clear") else sel.getValue("set")
        val props = template.jsonArray.map { row ->
            val r = row.jsonArray
            SelectionProp(
                layer = r[0].jsonPrimitive.content,
                kind = when (r[1].jsonPrimitive.content) {
                    "paint" -> SelectionProp.Kind.Paint
                    "filter" -> SelectionProp.Kind.Filter
                    else -> error("unknown selection kind ${r[1]}")
                },
                property = (r[2] as? JsonPrimitive)?.takeIf { it !is JsonNull }?.content,
                value = substitute(r[3], addr),
            )
        }
        val clones = props.mapNotNull { p ->
            val clone = CLONES[p.layer] ?: return@mapNotNull null
            p.copy(layer = clone)
        }
        return props + clones
    }

    private fun substitute(e: JsonElement, addr: String?): JsonElement = when (e) {
        is JsonArray -> JsonArray(e.map { substitute(it, addr) })
        is JsonPrimitive -> when {
            e.isString && e.content == "ADDR" -> JsonPrimitive(addr ?: "")
            e.isString && e.content == "DIM" -> JsonPrimitive(dim)
            else -> e
        }
        else -> e
    }

    companion object {
        const val CELLS = "cells"
        const val CELLS_LAYER = "cells"
        const val CELL_COUNT_LAYER = "cell-count"
        private val CLONES = mapOf("clusters" to CELLS_LAYER, "cluster-count" to CELL_COUNT_LAYER)
        private val MINI_MAP_LAYERS = setOf("route", "end-dots", "end-labels")

        fun parse(json: String): MapStyleSpec = MapStyleSpec(Json.parseToJsonElement(json).jsonObject)

        private fun JsonObject.obj(key: String): JsonObject = getValue(key).jsonObject
        private val JsonObject.id: String get() = getValue("id").jsonPrimitive.content
        private fun JsonObject.cloneAs(id: String) =
            JsonObject(toMutableMap().apply { put("id", JsonPrimitive(id)); put("source", JsonPrimitive(CELLS)) })
    }
}
